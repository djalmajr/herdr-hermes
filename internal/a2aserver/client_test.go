func TestDialResolvesCard(t *testing.T) {
	store, _ := newTestStore(t)
	auth := newTableAuth(testSubject("caller-1"))
	s := newTestServer(t, store, auth, fakeRoutes{owner: "owner-ref-1"})
	ts := serveServer(t, s)

	c, err := Dial(ctxT(t), ts.URL, nil, &http.Client{Timeout: testHTTPClientTimeout})
	if err != nil {
		t.Fatalf("dial: %v", err)
	}
	defer c.Close()
	card := c.Card()
	if card == nil || card.Name != cardName {
		t.Fatalf("card = %+v, want name %s", card, cardName)
	}
	if len(card.SupportedInterfaces) != 1 {
		t.Fatalf("interfaces = %d, want 1", len(card.SupportedInterfaces))
	}
	if card.SupportedInterfaces[0].ProtocolBinding != a2a.TransportProtocolHTTPJSON {
		t.Errorf("binding = %s, want HTTP+JSON", card.SupportedInterfaces[0].ProtocolBinding)
	}
	if string(a2a.Version) != "1.0" {
		t.Fatalf("SDK version = %s, want 1.0", a2a.Version)
	}
	if string(card.SupportedInterfaces[0].ProtocolVersion) != "1.0" {
		t.Errorf("protocol version = %s, want 1.0", card.SupportedInterfaces[0].ProtocolVersion)
	}
}

func TestCredentialSourceSetsHeaderAndErrors(t *testing.T) {
	store, _ := newTestStore(t)
	auth := newTableAuth(testSubject("caller-1"))
	s := newTestServer(t, store, auth, fakeRoutes{owner: "owner-ref-1"})
	ts := serveServer(t, s)

	// The header is applied: the server authenticates the bearer token.
	ok := dialClient(t, ts.URL, auth, "caller-1")
	if _, err := ok.Get(ctxT(t), "t-1"); !errors.Is(err, a2a.ErrTaskNotFound) {
		t.Errorf("get err = %v, want ErrTaskNotFound (authenticated, unknown task)", err)
	}

	// A source error fails the call before the network request.
	broken := staticCredential{err: errors.New("credential source broken")}
	c, err := Dial(ctxT(t), ts.URL, broken, &http.Client{Timeout: testHTTPClientTimeout})
	if err != nil {
		t.Fatalf("dial: %v", err)
	}
	defer c.Close()
	if _, err := c.Get(ctxT(t), "t-1"); err == nil || !errors.Is(err, broken.err) {
		t.Errorf("get err = %v, want the credential source error", err)
	}
}

func TestClientSendWork(t *testing.T) {
	store, _ := newTestStore(t)
	auth := newTableAuth(testSubject("caller-1"))
	s := newTestServer(t, store, auth, fakeRoutes{owner: "owner-ref-1"})
	ts := serveServer(t, s)
	c := dialClient(t, ts.URL, auth, "caller-1")

	// An explicit message id and the correlation metadata. The state
	// may already be working (the immediate-return interrupt reads the
	// stored task, the executor yields both events).
	task := sendTask(t, c, SendInput{
		Project: "org/repo", Job: "job-1", Session: "s-1",
		Epoch: 1, Seq: 1, MessageID: "m-1", Text: "hello",
	})
	if task.Status.State != a2a.TaskStateSubmitted && task.Status.State != a2a.TaskStateWorking {
		t.Errorf("state = %s, want submitted or working", task.Status.State)
	}
	if task.Metadata[a2acore.MetaProject] != "org/repo" || task.Metadata[a2acore.MetaJob] != "job-1" {
		t.Errorf("task metadata = %v, want project and job", task.Metadata)
	}
	got, err := c.Get(ctxT(t), string(task.ID))
	if err != nil {
		t.Fatalf("get: %v", err)
	}
	if len(got.History) != 1 || got.History[0].ID != "m-1" {
		t.Errorf("history = %+v, want one message m-1", got.History)
	}

	// An empty message id is generated by the client.
	second := sendTask(t, c, SendInput{Project: "org/repo", Session: "s-1", Epoch: 1, Seq: 2, Text: "again"})
	if second.History[0].ID == "" {
		t.Error("generated message id is empty")
	}
	if string(second.ID) == string(task.ID) {
		t.Error("second send created the same task id")
	}
}

func TestReturnImmediatelyForcedByServer(t *testing.T) {
	// A raw SDK client without any send config: the server interceptor
	// must force ReturnImmediately, so the call returns the submitted
	// task while the execution parks (a blocking call would hang until
	// the context deadline).
	store, _ := newTestStore(t)
	auth := newTableAuth(testSubject("caller-1"))
	s := newTestServer(t, store, auth, fakeRoutes{owner: "owner-ref-1"})
	ts := serveServer(t, s)

	orig := s.Card()
	card := *orig
	card.SupportedInterfaces = append([]*a2a.AgentInterface(nil), orig.SupportedInterfaces...)
	card.SupportedInterfaces[0] = a2a.NewAgentInterface(ts.URL, a2a.TransportProtocolHTTPJSON)
	raw, err := a2aclient.NewFromCard(ctxT(t), &card,
		a2aclient.WithConfig(a2aclient.Config{PreferredTransports: []a2a.TransportProtocol{a2a.TransportProtocolHTTPJSON}}))
	if err != nil {
		t.Fatalf("raw client: %v", err)
	}
	defer raw.Destroy()
	ctx := a2aclient.AttachServiceParams(ctxT(t), a2aclient.ServiceParams{
		"authorization": []string{auth.token("caller-1")},
	})
	// The client did not ask to return immediately: the server forced
	// it, so the call returns quickly with the task in a non-terminal
	// state while the execution parks (a blocking call would wait for
	// the context deadline).
	start := time.Now()
	res, err := raw.SendMessage(ctx, &a2a.SendMessageRequest{
		Message: &a2a.Message{
			ID:    "m-1",
			Role:  a2a.MessageRoleUser,
			Parts: a2a.ContentParts{a2a.NewTextPart("force me")},
			Metadata: map[string]any{
				a2acore.MetaProject: "org/repo",
				a2acore.MetaSession: "s-1",
				a2acore.MetaEpoch:   float64(1),
				a2acore.MetaSeq:     float64(1),
			},
		},
		// No Config: ReturnImmediately is not asked by the client.
	})
	if err != nil {
		t.Fatalf("send: %v", err)
	}
	if took := time.Since(start); took > 5*time.Second {
		t.Errorf("send took %s, want an immediate return", took)
	}
	task, ok := res.(*a2a.Task)
	if !ok {
		t.Fatalf("result = %T, want *a2a.Task", res)
	}
	if task.Status.State.Terminal() {
		t.Errorf("state = %s, want a non-terminal state", task.Status.State)
	}
	if s.LiveExecutions() == 0 {
		t.Error("the execution did not park (ReturnImmediately not forced)")
	}
}
